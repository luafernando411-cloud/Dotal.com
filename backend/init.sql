CREATE TABLE IF NOT EXISTS users (
    id VARCHAR(36) PRIMARY KEY,
    cpf VARCHAR(11) UNIQUE,
    full_name VARCHAR(200),
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'blocked')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admins (
    id VARCHAR(36) PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'admin' CHECK (role = 'admin'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS access_logs (
    id VARCHAR(36) PRIMARY KEY,
    account_type VARCHAR(16) NOT NULL,
    identifier_hash VARCHAR(64) NOT NULL,
    ip_hash VARCHAR(64) NOT NULL,
    success BOOLEAN NOT NULL,
    event VARCHAR(32) NOT NULL DEFAULT 'login',
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS census_records (
    id VARCHAR(36) PRIMARY KEY,
    owner_id VARCHAR(36) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    protocol VARCHAR(32) NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    cpf VARCHAR(14) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(24),
    category VARCHAR(24) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'Pendente',
    region VARCHAR(32),
    city VARCHAR(100),
    state VARCHAR(2),
    payload JSON NOT NULL DEFAULT '{}'::json,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS census_steps (
    id VARCHAR(36) PRIMARY KEY,
    census_id VARCHAR(36) NOT NULL REFERENCES census_records(id) ON DELETE CASCADE,
    step_name VARCHAR(80) NOT NULL,
    data JSON NOT NULL DEFAULT '{}'::json,
    status VARCHAR(40) NOT NULL DEFAULT 'Pendente',
    feedback TEXT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_census_step_name UNIQUE (census_id, step_name)
);

CREATE TABLE IF NOT EXISTS census_documents (
    id VARCHAR(36) PRIMARY KEY,
    census_id VARCHAR(36) NOT NULL REFERENCES census_records(id) ON DELETE CASCADE,
    document_type VARCHAR(60) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    stored_name VARCHAR(255) NOT NULL UNIQUE,
    content_type VARCHAR(120),
    size_bytes INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_users_cpf ON users(cpf);
CREATE INDEX IF NOT EXISTS ix_users_email ON users(email);
CREATE INDEX IF NOT EXISTS ix_admins_email ON admins(email);
CREATE INDEX IF NOT EXISTS ix_access_logs_ip_hash ON access_logs(ip_hash);
CREATE INDEX IF NOT EXISTS ix_access_logs_occurred_at ON access_logs(occurred_at);
CREATE INDEX IF NOT EXISTS ix_census_records_owner_id ON census_records(owner_id);
CREATE UNIQUE INDEX IF NOT EXISTS ix_census_records_protocol ON census_records(protocol);
CREATE INDEX IF NOT EXISTS ix_census_records_full_name ON census_records(full_name);
CREATE UNIQUE INDEX IF NOT EXISTS ix_census_records_cpf ON census_records(cpf);
CREATE INDEX IF NOT EXISTS ix_census_records_status ON census_records(status);
CREATE INDEX IF NOT EXISTS ix_census_records_region ON census_records(region);
CREATE INDEX IF NOT EXISTS ix_census_records_city ON census_records(city);
CREATE INDEX IF NOT EXISTS ix_census_records_status_category
    ON census_records(status, category);
CREATE INDEX IF NOT EXISTS ix_census_steps_census_id ON census_steps(census_id);
CREATE INDEX IF NOT EXISTS ix_census_steps_status ON census_steps(status);
CREATE INDEX IF NOT EXISTS ix_census_documents_census_id ON census_documents(census_id);
CREATE INDEX IF NOT EXISTS ix_census_documents_document_type ON census_documents(document_type);

